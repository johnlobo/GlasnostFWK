#!/usr/bin/env python3
"""Generate Z80 video constants/tables and an auditable memory report."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from video_model import address, contiguous_runs, number, segments, visible_addresses, window_addresses


def load_profile(path: Path) -> dict:
    profile = json.loads(path.read_text(encoding="utf-8"))
    required = {"name", "mode", "width_pixels", "width_bytes", "height_lines", "segments", "memory_windows"}
    missing = required - profile.keys()
    if missing:
        raise ValueError(f"missing profile keys: {', '.join(sorted(missing))}")
    if profile["mode"] != 0:
        raise ValueError("only Mode 0 is currently supported")
    if profile["width_pixels"] != profile["width_bytes"] * 2:
        raise ValueError("Mode 0 requires width_pixels == width_bytes * 2")
    if profile["height_lines"] > 256 and profile.get("coordinate_bits", 8) < 16:
        raise ValueError("height above 256 requires 16-bit coordinates")
    coverage: list[int] = []
    for segment in segments(profile):
        coverage.extend(range(segment.y_start, segment.y_start + segment.height))
    if coverage != list(range(profile["height_lines"])):
        raise ValueError("segments must cover every y line exactly once and in order")
    return profile


def validate(profile: dict) -> dict:
    visible = visible_addresses(profile)
    expected = profile["width_bytes"] * profile["height_lines"]
    if len(visible) != expected:
        raise ValueError(f"visible address alias: {expected - len(visible)} bytes overlap")
    windows = window_addresses(profile)
    outside = visible - windows
    if outside:
        raise ValueError(f"{len(outside)} visible bytes fall outside declared video windows")
    reserved = set()
    for region in profile.get("reserved", []):
        reserved.update(range(number(region["start"]), number(region["end"]) + 1))
    collision = visible & reserved
    if collision:
        raise ValueError(f"visible memory overlaps {len(collision)} reserved bytes")
    holes = windows - visible
    return {
        "visible_bytes": len(visible),
        "visible_runs": contiguous_runs(visible),
        "hole_bytes": len(holes),
        "hole_runs": contiguous_runs(holes),
        "minimum": min(visible),
        "maximum": max(visible),
    }


def asm(profile: dict, report: dict) -> str:
    crtc_registers = profile.get("crtc", {}).get("registers", {})
    page_command = profile.get("crtc", {}).get("video_page_command")
    lines = [
        ";; Generated by tools/gen_video.py. Do not edit.",
        f"FWK_VIDEO_MODE = {profile['mode']}",
        f"FWK_VIDEO_WIDTH_PIXELS = {profile['width_pixels']}",
        f"FWK_VIDEO_WIDTH_BYTES = {profile['width_bytes']}",
        f"FWK_VIDEO_HEIGHT = {profile['height_lines']}",
        f"FWK_VIDEO_COORD_BITS = {profile.get('coordinate_bits', 8)}",
        f"FWK_VIDEO_VISIBLE_BYTES = {report['visible_bytes']}",
        f"FWK_VIDEO_VISIBLE_RUN_COUNT = {len(report['visible_runs'])}",
        f"FWK_VIDEO_CRTC_REG_COUNT = {len(crtc_registers)}",
        f"FWK_VIDEO_HAS_PAGE_COMMAND = {1 if page_command is not None else 0}",
        f"FWK_VIDEO_PAGE_COMMAND = {number(page_command) if page_command is not None else 0}",
        ".area _CODE",
        "fwk_video_crtc_table::",
    ]
    for name, value in sorted(crtc_registers.items(), key=lambda item: int(item[0][1:])):
        lines.append(f"    .db {int(name[1:])}, {value}")
    lines.append("fwk_video_line_table::")
    for y in range(profile["height_lines"]):
        lines.append(f"    .dw 0x{address(profile, 0, y):04X} ;; y={y}")
    lines.append("fwk_video_visible_regions::")
    for start, end in report["visible_runs"]:
        lines.append(f"    .dw 0x{start:04X}, 0x{end - start + 1:04X}")
    lines.append("    .dw 0, 0")
    return "\n".join(lines) + "\n"


def markdown(profile: dict, report: dict) -> str:
    out = [
        f"# Video memory report: {profile['name']}", "",
        f"- Status: `{profile.get('status', 'unspecified')}`",
        f"- Mode: {profile['mode']}",
        f"- Geometry: {profile['width_pixels']}x{profile['height_lines']} ({profile['width_bytes']} bytes/line)",
        f"- Visible bytes: {report['visible_bytes']}",
        f"- Address span: `0x{report['minimum']:04X}`-`0x{report['maximum']:04X}`",
        f"- Declared-window holes: {report['hole_bytes']} bytes in {len(report['hole_runs'])} runs", "",
        "## Visible regions", "", "| Start | End | Bytes |", "|---:|---:|---:|",
    ]
    out += [f"| `0x{s:04X}` | `0x{e:04X}` | {e-s+1} |" for s, e in report["visible_runs"]]
    out += ["", "## Non-visible regions in declared video windows", "", "| Start | End | Bytes |", "|---:|---:|---:|"]
    out += [f"| `0x{s:04X}` | `0x{e:04X}` | {e-s+1} |" for s, e in report["hole_runs"]]
    if profile.get("crtc", {}).get("evidence"):
        out += ["", "## CRTC evidence boundary", "", profile["crtc"]["evidence"]]
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("profile", type=Path)
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args()
    profile = load_profile(args.profile)
    report = validate(profile)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    stem = profile["name"]
    (args.out_dir / f"{stem}.inc").write_text(asm(profile, report), encoding="utf-8")
    (args.out_dir / f"{stem}.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    (args.out_dir / f"{stem}.md").write_text(markdown(profile, report), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
