#!/usr/bin/env python3
"""Open the image built for one example in an external CPC emulator.

The emulator is never bundled: pick it with --emulator, with the
GLASNOST_EMULATOR environment variable, with `make run GLASNOST_EMULATOR=...`
or let the tool find AmSpiriT-Lite next to the repository, as the optional
smoke test does. When no emulator is available the image path is printed so it
can be opened by hand.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_EMULATOR = ROOT.parent / "tools" / "amspirit-lite" / "run.sh"
EMULATOR_COMMANDS = ("amspirit-lite", "amspirit", "macape", "cpct_macape")
MACAPE_CANDIDATES = (
    Path("/Applications/MacAPE.app/Contents/MacOS/MacAPE"),
    Path.home() / "Proyectos" / "macape" / "tools" / "macape",
    Path.home() / "Proyectos" / "macape" / "build" / "MacAPE.app" / "Contents" / "MacOS" / "MacAPE",
)


def project_name(example: str) -> str:
    manifest = ROOT / "examples" / example / "example.json"
    if not manifest.is_file():
        raise SystemExit(f"No existe el ejemplo {example}: falta {manifest.relative_to(ROOT)}")
    return json.loads(manifest.read_text(encoding="utf-8"))["name"]


def example_images(name: str) -> list[Path]:
    build = ROOT / ".build" / name
    return [build / f"{name}.cdt", build / f"{name}.dsk"]


def select_image(name: str, requested: str | None) -> Path:
    available = [path for path in example_images(name) if path.is_file()]
    if not available:
        raise SystemExit(
            f"No hay imagen construida para {name}: ejecute `make` en examples/{name}."
        )
    if requested is not None:
        wanted = ROOT / ".build" / name / f"{name}.{requested}"
        if not wanted.is_file():
            formats = ", ".join(path.suffix.lstrip(".") for path in available)
            raise SystemExit(
                f"No hay imagen .{requested} construida para {name}; disponibles: {formats}. "
                f"Ejecute `make` en examples/{name}."
            )
        return wanted
    # CDT first: the tape generated by 2cdt autoruns, while a DSK needs RUN".
    return available[0]


def find_emulator(explicit: str | None) -> str | None:
    candidate = explicit or os.environ.get("GLASNOST_EMULATOR", "").strip()
    if candidate:
        path = Path(candidate).expanduser()
        if not path.is_file():
            raise SystemExit(f"El emulador indicado no existe: {path}")
        return str(path)
    if DEFAULT_EMULATOR.is_file():
        return str(DEFAULT_EMULATOR)
    for command in EMULATOR_COMMANDS:
        found = shutil.which(command)
        if found:
            return found
    for candidate in MACAPE_CANDIDATES:
        if candidate.is_file():
            return str(candidate)
    return None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("example", help="nombre del ejemplo, por ejemplo minimal")
    parser.add_argument("--emulator", help="ejecutable del emulador a usar")
    parser.add_argument(
        "--image",
        choices=("cdt", "dsk"),
        help="formato a abrir; por defecto CDT si existe y DSK si no",
    )
    parser.add_argument(
        "--print-path",
        action="store_true",
        help="solo mostrar la imagen seleccionada, sin abrir emulador",
    )
    args = parser.parse_args()

    name = project_name(args.example)
    image = select_image(name, args.image)
    emulator = find_emulator(args.emulator)

    if args.print_path or emulator is None:
        if emulator is None and not args.print_path:
            print(
                "No se encontró ningún emulador. Abra la imagen anterior o indique uno con "
                "`make run GLASNOST_EMULATOR=/ruta/al/emulador`.",
                file=sys.stderr,
            )
        print(image)
        return 0

    print(f"{emulator} {image}")
    command = [emulator, str(image)]
    base = Path(emulator).name.lower()
    if base == "macape":
        if image.suffix.lower() == ".dsk":
            command.append("/A")
        noi = ROOT / ".build" / name / "obj" / f"{name}.noi"
        if noi.is_file():
            command.append(f"/SYM:{noi}")
    return subprocess.run(command).returncode


if __name__ == "__main__":
    raise SystemExit(main())
