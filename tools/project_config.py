#!/usr/bin/env python3
"""Validate project capabilities and generate their Z80 configuration."""

from __future__ import annotations

from dataclasses import dataclass


TRANSPARENCY_ADDRESS = 0x0100
BANK_STUB_START = 0x0200
BANK_STUB_END = 0x0215
BANK_PROBE = 0x4000
DEFAULT_CODE_START = 0x0200
BANKED_CODE_START = BANK_STUB_END + 1


@dataclass(frozen=True)
class ProjectCapabilities:
    transparency_pen: int | None
    extended_memory: bool

    @property
    def code_start(self) -> int:
        return BANKED_CODE_START if self.extended_memory else DEFAULT_CODE_START


def parse_capabilities(manifest: dict, video_mode: int) -> ProjectCapabilities:
    transparency = manifest.get("transparency")
    pen: int | None = None
    if transparency is not None:
        if not isinstance(transparency, dict) or set(transparency) != {"pen"}:
            raise ValueError("transparency must be an object containing only pen")
        pen = transparency["pen"]
        if isinstance(pen, bool) or not isinstance(pen, int) or not 0 <= pen <= 15:
            raise ValueError("transparency pen must be an integer from 0 to 15")
        if video_mode != 0:
            raise ValueError("configurable transparency currently requires Mode 0")

    extended = manifest.get("extended_memory", False)
    if not isinstance(extended, bool):
        raise ValueError("extended_memory must be true or false")
    return ProjectCapabilities(pen, extended)


def mode0_mask_table(pen: int) -> bytes:
    """Return masks for both packed Mode 0 pixels for every source byte."""
    if isinstance(pen, bool) or not isinstance(pen, int) or not 0 <= pen <= 15:
        raise ValueError("Mode 0 transparent pen must be an integer from 0 to 15")

    def packed_pen(value: int, positions: tuple[int, int, int, int]) -> int:
        return sum(((value >> bit) & 1) << weight for weight, bit in enumerate(positions))

    table = bytearray()
    for value in range(256):
        left = packed_pen(value, (7, 3, 5, 1))
        right = packed_pen(value, (6, 2, 4, 0))
        mask = (0xAA if left == pen else 0) | (0x55 if right == pen else 0)
        table.append(mask)
    return bytes(table)


def generate_include(capabilities: ProjectCapabilities) -> str:
    enabled = capabilities.transparency_pen is not None
    lines = [
        ";; Generated by tools/build_examples.py; do not edit.",
        f"FWK_TRANSPARENCY_ENABLED = {1 if enabled else 0}",
        f"FWK_EXTENDED_MEMORY_ENABLED = {1 if capabilities.extended_memory else 0}",
        f"FWK_PROJECT_CODE_START = 0x{capabilities.code_start:04X}",
    ]
    if enabled:
        lines.extend(
            [
                f"FWK_TRANSPARENCY_TABLE = 0x{TRANSPARENCY_ADDRESS:04X}",
                f"FWK_TRANSPARENCY_PEN = {capabilities.transparency_pen}",
            ]
        )
    return "\n".join(lines) + "\n"


def _db_lines(data: bytes) -> list[str]:
    return [
        "    .db " + ",".join(f"0x{value:02X}" for value in data[offset : offset + 16])
        for offset in range(0, len(data), 16)
    ]


def generate_source(capabilities: ProjectCapabilities) -> str:
    lines = [
        ";; Generated project initialization; do not edit.",
        ".module fwk_project_config",
        '.include "project_config.inc"',
        ".globl fwk_system_init",
    ]
    if capabilities.extended_memory:
        lines.append(".globl fwk_bank_init")
    lines.extend(["", ".area _CODE", "", "fwk_project_init::", "    call fwk_system_init"])
    if capabilities.transparency_pen is not None:
        lines.append("    call _fwk_transparency_init")
    if capabilities.extended_memory:
        lines.append("    call fwk_bank_init")
    lines.append("    ret")

    if capabilities.transparency_pen is not None:
        lines.extend(
            [
                "",
                ";; Installed exactly once by fwk_project_init after firmware shutdown.",
                "_fwk_transparency_init:",
                "    ld hl, #_fwk_transparency_table_source",
                "    ld de, #FWK_TRANSPARENCY_TABLE",
                "    ld bc, #256",
                "    ldir",
                "    ret",
                "",
                "_fwk_transparency_table_source:",
            ]
        )
        lines.extend(_db_lines(mode0_mask_table(capabilities.transparency_pen)))
    return "\n".join(lines) + "\n"
