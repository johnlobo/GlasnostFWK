#!/usr/bin/env python3
"""Validate a declarative bank/resource manifest and emit an assembly table."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def num(value: int | str) -> int:
    return value if isinstance(value, int) else int(value, 0)


def overlap(a0: int, a1: int, b0: int, b1: int) -> bool:
    return a0 <= b1 and b0 <= a1


def validate(data: dict) -> list[dict]:
    if data.get("profile") not in {"64k", "128k"}:
        raise ValueError("profile must be '64k' or '128k'")
    resources = data.get("resources", [])
    bank_start = num(data["bank_window"]["start"])
    bank_end = num(data["bank_window"]["end"])
    seen_ids: set[str] = set()
    by_bank: dict[int, list[tuple[int, int, str]]] = {}
    destinations: list[tuple[int, int, str]] = []
    for item in resources:
        rid = item["id"]
        if rid in seen_ids:
            raise ValueError(f"duplicate resource id: {rid}")
        seen_ids.add(rid)
        bank = item["bank"]
        if data["profile"] == "64k" and bank != 0:
            raise ValueError(f"{rid}: bank {bank} is unavailable in 64k profile")
        if not 0 <= bank <= 3:
            raise ValueError(f"{rid}: bank must be 0..3")
        size = item["size"]
        if not 0 < size <= bank_end - bank_start + 1:
            raise ValueError(f"{rid}: invalid size {size}")
        offset = num(item["bank_offset"])
        if offset < 0 or bank_start + offset + size - 1 > bank_end:
            raise ValueError(f"{rid}: bank payload exceeds 0x{bank_start:04X}..0x{bank_end:04X}")
        align = item.get("alignment", 1)
        destination = num(item["destination"])
        if align <= 0 or align & (align - 1):
            raise ValueError(f"{rid}: alignment must be a positive power of two")
        if destination % align:
            raise ValueError(f"{rid}: destination 0x{destination:04X} violates alignment {align}")
        bank_range = (offset, offset + size - 1, rid)
        for start, end, other in by_bank.setdefault(bank, []):
            if overlap(start, end, bank_range[0], bank_range[1]):
                raise ValueError(f"{rid}: overlaps {other} in bank {bank}")
        by_bank[bank].append(bank_range)
        dest_range = (destination, destination + size - 1, rid)
        for start, end, other in destinations:
            if overlap(start, end, dest_range[0], dest_range[1]):
                raise ValueError(f"{rid}: destination overlaps {other}")
        for region in data.get("normal_reserved", []):
            if overlap(num(region["start"]), num(region["end"]), dest_range[0], dest_range[1]):
                raise ValueError(f"{rid}: destination overlaps reserved region {region['name']}")
        destinations.append(dest_range)
    return resources


def emit(resources: list[dict]) -> str:
    lines = [
        ";; Generated by tools/gen_resources.py. Do not edit.",
        f"FWK_RESOURCE_COUNT = {len(resources)}",
        ".area _CODE",
        "fwk_resource_table::",
        ";; bank, source address, destination, size",
    ]
    for item in resources:
        source = 0x4000 + num(item["bank_offset"])
        destination = num(item["destination"])
        lines += [
            f"fwk_resource_{item['id']}::",
            f"    .db {item['bank']}",
            f"    .dw 0x{source:04X}, 0x{destination:04X}, {item['size']}",
        ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("manifest", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    data = json.loads(args.manifest.read_text(encoding="utf-8"))
    resources = validate(data)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(emit(resources), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
